    }

    public static function isBirthdayToday(): bool
    {
        $month = (int) ($_ENV['BIRTHDAY_MONTH'] ?? 10);
        $day = (int) ($_ENV['BIRTHDAY_DAY'] ?? 30);
        return date('n') === (string) $month && date('j') === (string) $day;
    }
