    public static function keyboard(string $key): array
    {
        $scene = self::scene($key);
        $next = $scene['next'];
        return [
            'inline_keyboard' => [[
                ['text' => $scene['button'], 'callback_data' => $next === null ? 'story:letter' : 'story:' . $next],
            ]],
        ];
    }

    public static function countdownIntro(): string
    {
